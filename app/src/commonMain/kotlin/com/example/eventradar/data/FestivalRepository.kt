    fun findArtistsInLineup(entry: String): List<Artist> {
        val showNames = listOf(
            "Razor Riot", "Sonic Surge", "Achterlijk Hard", "Heist Night", "Bombsquad", 
            "The Target List", "Mutation", "Bounce Of Steel", "New Breed Of Terror", 
            "Bassdrum Demolition", "Patient Zero", "New Live Experience", "The Ultimate Mashup",
            "Journey", "Slowtempo Special", "15 Years Chasin The Bass", "Spoontech Legacy",
            "Timelapse", "My True DNA", "Universe LIVE", "Evolved Euphoria", "Our World LIVE",
            "Holy Dreams LIVE", "Rave Reactor", "Forsaken Two", "Early Uptempo", 
            "Ode To The Past", "Hardcore Goldschool", "Locked & Loaded", "Aggression Therapy LIVE",
            "VIBES", "Infinity", "Ascension LIVE", "The Legacy Trip", "built to break",
            "Rise of Olympass", "Warbound LIVE", "777 LIVE", "A Symphony of Screams",
            "T3ST SUBJ3CT 3", "Polish Punisher II", "Going Apeshit", "still the one man army",
            "Sh!t Happens", "Rammeroni", "Achterlijk Hard", "The Opening", "Closing"
        )

        var cleanEntry = entry
        showNames.forEach { showName ->
            cleanEntry = cleanEntry.replace(" pres. $showName", "", ignoreCase = true)
                .replace(" presents $showName", "", ignoreCase = true)
                .replace(" Presents $showName", "", ignoreCase = true)
                .replace(" presents: $showName", "", ignoreCase = true)
                .replace(" Presents: $showName", "", ignoreCase = true)
                .replace(" pres $showName", "", ignoreCase = true)
        }

        cleanEntry = cleanEntry
            .replace(" LIVE", "", ignoreCase = true)
            .replace(" presents ", " vs ", ignoreCase = true)
            .replace(" Presents: ", " vs ", ignoreCase = true)
            .replace(" ft. ", " vs ", ignoreCase = true)
            .replace(" ft ", " vs ", ignoreCase = true)
            .replace(" & ", " vs ", ignoreCase = true)
            .replace(" b2b ", " vs ", ignoreCase = true)
            .replace(" vs. ", " vs ", ignoreCase = true)
            .replace(" Vs ", " vs ", ignoreCase = true)
            .replace(" (Millennium Set)", "", ignoreCase = true)
            .replace(" (Millennium )", "", ignoreCase = true)
            .replace(" (Millennium)", "", ignoreCase = true)
            .replace(" Album Showcase", "", ignoreCase = true)
            .replace(" 10 Years Special", "", ignoreCase = true)
            .replace(" 10 Years", "", ignoreCase = true)
            .replace(" 15 Years", "", ignoreCase = true)
            .replace("15 Years Of ", "", ignoreCase = true)
            .replace(" (Classics)", "", ignoreCase = true)
            .replace(" pres. ", " vs ", ignoreCase = true)
            .replace(" (Early)", "", ignoreCase = true)

        val parts = cleanEntry.split(" vs ", " vs. ", " Vs ", ", ", " and ")
        return parts.flatMap { part ->
            val trimmed = part.trim()
            if (trimmed.isEmpty()) return@flatMap emptyList()
            
            // Try to find the artist
            val found = artists.find { it.name.equals(trimmed, ignoreCase = true) }
                ?: artists.find { 
                    it.name.equals("DJ $trimmed", ignoreCase = true) ||
                    it.name.equals("MC $trimmed", ignoreCase = true) ||
                    trimmed.equals("DJ ${it.name}", ignoreCase = true) ||
                    trimmed.equals("MC ${it.name}", ignoreCase = true)
                }
            
            if (found != null) {
                listOf(found)
            } else {
                // Return a dynamic artist with placeholder image
                listOf(Artist(name = trimmed, imageUrl = "https://via.placeholder.com/300?text=${trimmed.replace(" ", "+")}"))
            }
        }
    }
